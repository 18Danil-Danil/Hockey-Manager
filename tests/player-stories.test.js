const assert = require('assert');
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const source = fs.readFileSync(path.join(__dirname, '..', 'engine/player-stories.js'), 'utf8');
const teams = [{id:1,name:'Рязань',roster:[]},{id:2,name:'Химик',roster:[]}];
const player=(id,name,age,position,stats,careerStats={})=>({id,name,age,position,ovr:75,form:90,morale:80,stats:{gp:20,goals:0,assists:10,points:15,wins:0,saves:0,shotsAgainst:0,...stats},careerStats:{goals:0,points:0,wins:0,...careerStats}});
const young=player(10,'Иван Молодой',20,'C',{points:18});
const veteran=player(11,'Пётр Ветеран',34,'LW',{points:4},{points:96,goals:0});
const goalie=player(12,'Сергей Вратарь',25,'G',{gp:15,saves:450,shotsAgainst:480,points:0});
teams[0].roster.push(young,veteran,goalie); teams[1].roster.push(player(20,'Игрок Химика',24,'C',{points:12}));
const news=[],inbox=[]; const G={playerTeamId:1,league:{season:'2026/27',teams,news:[],playerStoryFlags:{}}};
const context={G,addNews:(type,text,importance)=>news.push({type,text,importance}),addInboxMessage:(...args)=>inbox.push(args)};
vm.runInNewContext(source+'\nthis.runStories=generatePlayerStories;',context); context.runStories();
assert(news.some(n=>n.text.includes('Иван Молодой')&&n.text.toLowerCase().includes('прорыв')),'young breakout');
assert(news.some(n=>n.text.includes('Пётр Ветеран')&&n.text.includes('100')),'career milestone');
assert(news.some(n=>n.text.includes('Сергей Вратарь')&&n.type==='player_story'),'goalie story');
assert(inbox.some(message=>message[2].includes('Сергей Вратарь')&&message[3].includes('93.8%')),'goalie story details');
assert(inbox.length>=2,'managed-team stories should reach inbox');
const count=news.length; context.runStories(); assert.strictEqual(news.length,count,'no duplicate stories during season');
G.league.season='2027/28'; young.stats.points=22; context.runStories(); assert(news.length>count,'seasonal stories reset next season');
console.log('Player stories checks passed.');
